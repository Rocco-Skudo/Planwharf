'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { createOrchestrator } = require('./orchestrator.js');
const { createAttemptEngine } = require('./attempts.js');
const { assignmentSession, projectActivitySessions, readRecordedTail, SESSION_LIMIT, EVENT_LIMIT, TAIL_BYTES } = require('./activity-sessions.cjs');
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'pw-activity-sessions-'));
const execution = {
  megaTasks: [{ id: 'mega-a', projectId: 'a', taskId: 'job-a', status: 'COMPLETE' }, { id: 'mega-b', projectId: 'b', taskId: 'job-b', status: 'RUNNING' }],
  subTasks: [{ id: 'sub-a', megaTaskId: 'mega-a', type: 'AUDIT', status: 'COMPLETE', resultId: 'R-attempt-a', completedAt: '2026-10-16T10:00:00Z' }, { id: 'sub-b', megaTaskId: 'mega-b', type: 'IMPLEMENTATION', status: 'RUNNING' }],
  results: [], checkpoints: [], timeline: [], observations: {}
};
const result = { resultId: 'R-attempt-a', attemptId: 'attempt-a', megaTaskId: 'mega-a', subTaskId: 'sub-a', provider: 'codex', cli: 'exact-cli', status: 'COMPLETE', exitCode: 0, summary: 'Fixture report', filesChanged: [], tests: [], blockers: [], nextAction: '', createdAt: '2026-10-16T09:59:00Z' };
execution.results.push(result);
const part = { attemptId: 'attempt-a', megaTaskId: 'mega-a', subTaskId: 'sub-a', provider: 'codex', cli: 'exact-cli', modelId: 'stable-model-id', observedAlive: false, alive: false, startedAt: '2026-10-16T09:00:00Z', sessionId: 'original-session' };
const tail = JSON.stringify({ type: 'item.started', item: { type: 'command_execution', command: 'npm test' } }) + '\n' + JSON.stringify({ type: 'item.completed', item: { type: 'agent_message', text: '3 passed api_key=private-value' } });
(async () => {
  const log = path.join(dir, 'a.log'); fs.writeFileSync(log, tail); part.logPath = log;
  const projects = ['a', 'b'].map(id => ({ schema: 1, project: { id, name: id.toUpperCase() }, revisions: [{ id: 1, direction: 'Fixture', open: [], closed: [] }], tasks: [] }));
  const state = { projects: { a: { status: 'idle', dispatch: [part] }, b: { status: 'idle', dispatch: [{ modelId: 'old-model', alive: false }] } }, execution, workerHistory: [{ id: 'a', status: 'checkpointed', dispatch: [{ ...part, attemptId: 'old-attempt', startedAt: '2026-10-15T09:00:00Z' }] }] };
  fs.writeFileSync(path.join(dir, 'orchestrator.json'), JSON.stringify(state));
  const orch = createOrchestrator({ dir, readPlan: async () => ({ schema: 2, projects }), attempts: createAttemptEngine({ dir }), models: [], isProcessAlive: () => false });
  const snap = await orch.snapshot('a');
  assert.equal(snap.projects.length, 2);
  assert.equal(snap.projects[0].dispatch[0].alive, false);
  if (process.argv.includes('--baseline')) {
    assert.equal(snap.projects[0].dispatch[0].activitySession, undefined);
    console.log('BASELINE: recorded dispatch and history exist; structured assignment sessions absent. No provider calls, Git commands or process termination.');
    return;
  }
  const session = snap.projects[0].dispatch[0].activitySession;
  assert.equal(session.projectId, 'a');
  assert.equal(session.attemptId, 'attempt-a');
  assert.equal(session.role, 'reviewer');
  assert.equal(session.provider, 'codex');
  assert.equal(session.model, 'exact-cli');
  assert.equal(session.state, 'completed');
  assert.equal(session.validatedResultStatus, 'COMPLETE');
  assert.equal(session.events.length, 2);
  assert.equal(session.latestConfirmedActivity.classification, 'test');
  assert.equal(session.technicalEvidence.entries[0].command, 'npm test', 'Actual snapshot exposes the original command from this assignment log');
  assert.equal(session.technicalEvidence.entries[0].provenance, 'observed');
  assert.equal(session.reportedOutcomes[0].provenance, 'reported');
  assert.doesNotMatch(JSON.stringify(session), /private-value|a\.log/);
  assert.equal(fs.readFileSync(log, 'utf8'), tail, 'Raw source evidence remains unchanged');
  assert.equal(snap.projects[0].activitySessions.length, 2, 'Current and older retained dispatch visible, result deduplicated');
  assert.ok(snap.projects[0].activitySessions.every(session => session.projectId === 'a'));
  assert.ok(snap.projects[1].activitySessions.every(session => session.projectId === 'b'));
  assert.equal(snap.projects[1].dispatch[0].activitySession.provider, null, 'No retrofit from current model catalog');
  assert.deepEqual(snap.projects[1].dispatch[0].activitySession.technicalEvidence.entries, [], 'Another project never inherits this assignment source log');
  const build = overrides => assignmentSession({ projectId: 'a', execution, part: { ...part, ...overrides }, tail });
  assert.equal(build({}).completedAt, '2026-10-16T10:00:00Z');
  assert.equal(build({ cli: 'wrong-model' }).validatedResultStatus, null);
  assert.equal(build({ provider: 'wrong-provider' }).validatedResultStatus, null);
  const modelIdentityExecution = structuredClone(execution);
  modelIdentityExecution.results[0].assignedModelId = 'other-configured-model';
  const conflictingModel = assignmentSession({ projectId: 'a', part, execution: modelIdentityExecution });
  assert.equal(conflictingModel.validatedResultStatus, null);
  assert.notEqual(conflictingModel.state, 'completed');
  assert.match(conflictingModel.warnings.join(' '), /identity does not match/);
  assert.equal(assignmentSession({ projectId: 'a', part: { ...part, modelId: undefined }, execution: modelIdentityExecution }).validatedResultStatus, 'COMPLETE', 'Legacy dispatch without configured ID can use retained result identity');
  delete modelIdentityExecution.results[0].assignedModelId;
  assert.equal(assignmentSession({ projectId: 'a', part, execution: modelIdentityExecution }).validatedResultStatus, 'COMPLETE', 'Legacy result missing configured ID is not rejected solely for omission');
  assert.equal(build({ projectId: 'b' }), null);
  assert.equal(build({ megaTaskId: 'mega-b', subTaskId: 'sub-b' }), null);
  assert.equal(build({ observedAlive: true }).state, 'reviewing');
  const unvalidated = assignmentSession({ projectId: 'a', part: { observedAlive: false, pid: 77 }, row: { status: 'complete' }, tail: '5 passed' });
  assert.equal(unvalidated.state, 'unknown');
  assert.equal(unvalidated.validatedResultStatus, null);
  assert.equal(unvalidated.startedAt, null);
  assert.equal(unvalidated.role, null);
  assert.equal(unvalidated.events[0].provenance, 'reported');
  assert.equal(unvalidated.processState, 'ended');
  assert.equal(assignmentSession({ projectId: 'a', part: { observedAlive: false } }).processState, 'unknown', 'No PID is not evidence of process termination');
  assert.equal(build({ cli: 'wrong-model' }).recordedResultStatus, null);
  assert.equal(build({ stoppedByUser: true }).state, 'stopped');
  const invalidExecution = structuredClone(execution); invalidExecution.results[0].exitCode = 1;
  assert.equal(assignmentSession({ projectId: 'a', part, execution: invalidExecution }).validatedResultStatus, null);
  invalidExecution.results[0].exitCode = 0; invalidExecution.results[0].evidenceKind = 'TECHNICAL';
  assert.equal(assignmentSession({ projectId: 'a', part, execution: invalidExecution }).validatedResultStatus, null);
  const onlyResults = projectActivitySessions({ projectId: 'a', execution });
  assert.equal(onlyResults.length, 1); assert.equal(onlyResults[0].historical, true); assert.equal(onlyResults[0].events.length, 0);
  const bounded = build({});
  assert.ok(bounded.events.length <= EVENT_LIMIT);
  const manyHistory = Array.from({ length: 100 }, (_, i) => ({ id: 'a', dispatch: [{ attemptId: 'old-' + i }] }));
  assert.equal(projectActivitySessions({ projectId: 'a', history: manyHistory }).length, SESSION_LIMIT);
  assert.equal(readRecordedTail(__filename, dir), '', 'Outside notebook source cannot be loaded through session log paths');
  const largeLog = path.join(dir, 'large.log'); fs.writeFileSync(largeLog, 'x'.repeat(TAIL_BYTES * 3) + '\n' + tail);
  assert.ok(Buffer.byteLength(readRecordedTail(largeLog, dir)) <= TAIL_BYTES);
  assert.equal(readRecordedTail(largeLog, dir), tail);
  const restarted = createOrchestrator({ dir, readPlan: async () => ({ schema: 2, projects }), attempts: createAttemptEngine({ dir }), models: [], isProcessAlive: () => false });
  assert.equal((await restarted.snapshot()).projects[0].dispatch[0].activitySession.attemptId, 'attempt-a');
  console.log('OK: real snapshot wiring, stored assignment identity/roles, retained history, project boundaries, restart, bounded log reading, redaction and completion validation. Fixtures only.');
})().catch(error => { console.error(error); process.exitCode = 1; }).finally(() => {
  const target = path.resolve(dir);
  assert.ok(target.startsWith(path.resolve(os.tmpdir()) + path.sep) && path.basename(target).startsWith('pw-activity-sessions-'));
  fs.rmSync(target, { recursive: true, force: true });
});
