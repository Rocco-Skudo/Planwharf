'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
const Plan = require('../plan.js');
const { projectHome } = require('./project-home.cjs');
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'pw-progress-details-'));
const folder = path.join(dir, 'project'); fs.mkdirSync(folder);
const git = (...args) => execFileSync('git', ['-C', folder, ...args], { windowsHide: true, stdio: 'pipe' });
const commit = subject => { git('add', '.'); git('-c', 'user.name=Fixture', '-c', 'user.email=fixture@example.invalid', 'commit', '-m', subject); };
const event = (name, parameters) => JSON.stringify({ event: 'step_update', step_update: { state: 'DONE', step_type: 'tool', tool_name: name, tool_info: { parameters } } });
(async () => {
  git('init'); fs.writeFileSync(path.join(folder, 'Sayaku.ts'), 'export const greeting = "hello";\n'); commit('Create greeting fixture');
  const project = Plan.example(); project.project = { id: 'fixture', name: 'Fixture', folder }; project.tasks = [];
  const logPath = path.join(dir, 'worker.log');
  fs.writeFileSync(logPath, event('view_file', { AbsolutePath: path.join(folder, 'Sayaku.ts') }) + '\n');
  const row = { id: 'fixture', status: 'watching', jobId: 'audit', jobTitle: 'Audit Sayaku greeting behavior', dispatch: [{ label: 'Fixture worker', logPath, alive: false }] };
  const snapshot = { projects: [row] };
  const first = await projectHome(project, snapshot, null);
  fs.writeFileSync(path.join(folder, 'Sayaku.ts'), 'export const greeting = "Welcome";\n'); commit('Update greeting behavior');
  fs.writeFileSync(path.join(folder, 'Sayaku.test.ts'), 'fixture test source\n');
  const latest = project.revisions.at(-1);
  project.revisions.push({ ...latest, id: latest.id + 1, title: 'Greeting audit findings', state: 'Greeting behavior updated; integration review remains.', closed: [...latest.closed, 'Preserve the configured greeting.'] });
  row.status = 'complete';
  fs.appendFileSync(logPath, event('write_to_file', { TargetFile: path.join(folder, 'Sayaku.test.ts') }) + '\n' + event('run_command', { CommandLine: 'node Sayaku.test.ts' }) + '\n');
  const original = fs.readFileSync(logPath, 'utf8');
  const report = 'Greeting parsing now preserves the configured message.\n' + 'Fixture report details are retained without shortening.\n'.repeat(30);
  fs.appendFileSync(logPath, JSON.stringify({ event: 'result', result: { status: 'SUCCESS', response: report } }) + '\n');
  const withReport = fs.readFileSync(logPath, 'utf8');
  const returned = await projectHome(project, snapshot, first.current);
  assert.match(returned.since.details.join('\n'), /Update greeting behavior/);
  assert.match(returned.since.details.join('\n'), /Added locally: Sayaku.test.ts/);
  assert.match(returned.since.details.join('\n'), /Recorded progress: Greeting behavior updated/);
  assert.match(returned.since.details.join('\n'), /Decision recorded: Preserve the configured greeting/);
  assert.match(returned.progressDetails.actions.map(item => item.text).join('\n'), /writing project files: Sayaku.test.ts/);
  assert.match(returned.progressDetails.actions.map(item => item.text).join('\n'), /Finished running tests for Sayaku.test.ts/);
  assert.doesNotMatch(JSON.stringify(returned.progressDetails.actions), /step_update|conversation_id|tool_info/);
  assert.equal(returned.progress, project.revisions.at(-1).state, 'User-authored progress is preserved exactly');
  assert.equal(returned.progressDetails.reports[0].text, report, 'Full worker report is shown without summarization');
  assert.doesNotMatch(JSON.stringify(returned.current), /Fixture report details/, 'Full report is not duplicated into visit markers or request baselines');
  assert.equal(fs.readFileSync(logPath, 'utf8'), withReport, 'Raw historical execution evidence is unchanged');
  console.log('OK: concrete commit subjects, changed files, decisions and human worker actions since the prior visit, with original progress/logs preserved.');
})().catch(error => { console.error(error); process.exitCode = 1; }).finally(() => {
  const resolved = path.resolve(dir);
  assert.ok(resolved.startsWith(path.resolve(os.tmpdir()) + path.sep) && path.basename(resolved).startsWith('pw-progress-details-'));
  fs.rmSync(resolved, { recursive: true, force: true });
});
